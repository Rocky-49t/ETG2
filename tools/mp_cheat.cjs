// Two-tab multiplayer smoke test over the BroadcastChannel transport.
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
  const ctx = await browser.newContext({ viewport: { width: 1024, height: 600 } });
  const logs = [];
  const mk = async (name) => {
    const p = await ctx.newPage();
    p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') logs.push(`[${name} ${m.type()}] ${m.text()}`); });
    p.on('pageerror', e => logs.push(`[${name} pageerror] ${e.message}\n${(e.stack || '').split('\n').slice(0, 5).join('\n')}`));
    await p.goto('http://localhost:8080/index.html');
    await p.waitForFunction(() => document.getElementById('menu').classList.contains('show'), null, { timeout: 120000 });
    return p;
  };
  const A = await mk('host');
  const B = await mk('client');
  await A.click('#btnHost');
  await A.selectOption('#netMode', 'local');
  await A.fill('#seedInput', 'MPTEST');
  await A.click('#btnStart');
  await A.waitForFunction(() => document.getElementById('roomCode').textContent !== '-----', null, { timeout: 10000 });
  const code = await A.textContent('#roomCode');
  console.log('room', code);
  await B.bringToFront(); await B.evaluate(() => document.getElementById('btnJoin').click());
  await B.selectOption('#netMode', 'local');
  await B.fill('#joinCodeInput', code);
  await B.click('#btnDoJoin');
  await A.waitForFunction(() => document.querySelectorAll('#lobbyPlayers li').length >= 2, null, { timeout: 10000 });
  await B.click('#btnReady');
  await A.waitForTimeout(500);
  console.log('lobby A:', await A.textContent('#lobbyPlayers'));
  console.log('lobby B:', await B.textContent('#lobbyPlayers'));
  await A.click('#btnStart');
  await A.waitForTimeout(1000);
  await A.waitForFunction(() => window.__app.game && window.__app.game.levelId, null, { timeout: 120000 });
  await B.waitForFunction(() => window.__app.game && window.__app.game.levelId, null, { timeout: 120000 });
  const run = (P, cmd) => P.evaluate(cmd => { const a = window.__app; a.console.game = a.game; a.console.run(cmd); return [...a.console.log.children].slice(-1)[0]?.textContent; }, cmd);
  const can = P => P.evaluate(() => window.__app.game.canCheat());
  console.log('B give (denied):', await run(B, 'give pistol'), await can(B));
  console.log('A give before on:', await run(A, 'give pistol'));
  console.log('A cheats on:', await run(A, 'cheats on'));
  console.log('A players:', await A.evaluate(() => { const a = window.__app; a.console.run('players'); return [...a.console.log.children].slice(-2).map(e => e.textContent); }));
  console.log('A grant 2:', await run(A, 'grant 2'));
  await A.waitForTimeout(800);
  console.log('B can now:', await can(B));
  const before = await A.evaluate(() => window.__app.game.entities.list.size);
  console.log('B spawn:', await run(B, 'spawn hush'));
  await A.waitForTimeout(800);
  console.log('host entities', before, '->', await A.evaluate(() => window.__app.game.entities.list.size));
  console.log('A revoke all:', await run(A, 'revoke all'));
  await A.waitForTimeout(800);
  console.log('B can after revoke:', await can(B), await run(B, 'spawn hush'));
  // forged request from B after revoke must be ignored by the host
  const b2 = await A.evaluate(() => window.__app.game.entities.list.size);
  await B.evaluate(() => { const g = window.__app.game; g.request({ t: 'cheat', c: 'spawn', type: 'hush', n: 3, l: g.levelId, x: 20, z: 20 }); });
  await A.waitForTimeout(800);
  console.log('forged spawn ignored:', b2 === await A.evaluate(() => window.__app.game.entities.list.size));
  console.log(logs.slice(0, 30).join('\n'));
  await browser.close();
})();
